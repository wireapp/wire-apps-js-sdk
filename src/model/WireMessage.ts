import { QualifiedId } from "./QualifiedId.js";
import { MessageEncryptionAlgorithm } from "./protobuf/MessageEncryptionAlgorithm.js";
import Long from "long";

const appUserId = process.env['WIRE_SDK_USER_ID']!
const appUserDomain = process.env['WIRE_SDK_USER_DOMAIN']!
const appQualifiedId = new QualifiedId(appUserId, appUserDomain)

export type Item = object

/**
 * Interface for message types to be extended from that can be used as Ephemeral(self-deleting) messages
 */
interface Ephemeral {
  expiresAfterMillis?: number | null
}

/**
 * Interface for message types to be extended from that can be used to reply
 */
interface Replyable {
  timestamp: Date
}

/**
 * Interface for message types to be extended from that can be edited
 */
interface Editable {
  replacingMessageId: string
}

export interface Mention {
  userId: QualifiedId
  offset: number
  length: number
}

export interface LinkPreview {
  urlOffset: number
  url: string
  permanentUrl?: string | null
  title?: string | null
  summary?: string | null
  image?: LinkPreviewAsset | null
}

export interface LinkPreviewAsset {
  mimeType: string
  metadata?: AssetMetadata | null
  assetDataPath?: string | null
  assetDataSize: number | Long
  assetHeight: number
  assetWidth: number
  assetName?: string | null
  assetKey?: string | null
  assetToken?: string | null
  assetDomain?: string | null
  otrKey: Uint8Array
  sha256Key: Uint8Array
  encryptionAlgorithm: MessageEncryptionAlgorithm
}

export interface WireMessageBase {
  type: string
  /**
   * Message ID, auto-generated by the SDK when sending or populated from the received event
   */
  id: string

  /**
   * Conversation ID where the message is sent/received
   */
  conversationId: QualifiedId

  /**
   * User/App that sent the message, useful when receiving messages, ignored(auto-populated) when sending messages
   */
  sender?: QualifiedId
}

export class Unknown implements WireMessageBase {
  get id(): string {
    throw new Error("Unknown message, no ID")
  }

  get conversationId(): QualifiedId {
    throw new Error("Unknown message, no conversation")
  }

  get sender(): QualifiedId {
    throw new Error("Unknown message, no sender")
  }

  get timestamp(): Date {
    throw new Error("Unknown message, no timestamp")
  }

  readonly type = "unknown" as const
}

export class Ignored implements WireMessageBase {
  get id(): string {
    throw new Error("Ignored message, no ID")
  }

  get conversationId(): QualifiedId {
    throw new Error("Ignored message, no conversation")
  }

  get sender(): QualifiedId {
    throw new Error("Ignored message, no sender")
  }

  get timestamp(): Date {
    throw new Error("Ignored message, no timestamp")
  }

  readonly type = "ignored" as const
}

export interface TextMessage extends WireMessageBase, Item, Ephemeral, Replyable {
  type: 'text'
  text: string
  quotedMessageId?: string | null
  quotedMessageSha256?: Uint8Array | null
  mentions?: Mention[]
  linkPreviews?: LinkPreview[]
  expiresAfterMillis?: number | null
}

export const TextMessage = {
  create(
    params: {
      messageId?: string
      conversationId: QualifiedId
      text: string
      mentions?: Mention[]
      linkPreviews?: LinkPreview[]
      senderId?: QualifiedId
      expiresAfterMillis?: number | null | undefined,
      timestamp?: Date
    }
  ): TextMessage {
    return {
      type: 'text',
      id: params.messageId ?? crypto.randomUUID(),
      conversationId: params.conversationId,
      sender: params.senderId ?? appQualifiedId,
      text: params.text,
      mentions: params.mentions ?? [],
      linkPreviews: params.linkPreviews ?? [],
      timestamp: params.timestamp ?? new Date(),
      expiresAfterMillis: params.expiresAfterMillis ?? null
    }
  }
}

