export interface CompositeMessage extends WireMessageBase {
  type: "composite"
  items: Item[]
}

export const CompositeMessage = {
  create(
    params: {
      messageId?: string
      conversationId: QualifiedId
      text?: string
      itemList: Item[],
      senderId?: QualifiedId
    }
  ): CompositeMessage {
    const textItem = params.text
      ? TextMessage.create({
        conversationId: params.conversationId,
        text: params.text
      })
      : null

    return {
      type: "composite",
      id: params.messageId ?? crypto.randomUUID(),
      conversationId: params.conversationId,
      items: [...(textItem ? [textItem] : []), ...params.itemList],
      sender: params.senderId ?? appQualifiedId
    }
  }
}

